"""PHASE 4 -- is nest edge vorticity numerical contamination, or expected Davies shear?

The matched-domain investigation kept failing because the 22 m nest's boundary carried far more
vorticity than its interior.  Two hypotheses were live:

  (a) it is a BUG (boundary divergence from the projection / BC ordering), fixable;
  (b) it is INTRINSIC to Davies-zone nesting -- shear generated by nudging toward an interpolated
      parent field -- i.e. expected behaviour that a trusted-interior margin must exclude.

Evidence so far pointed at (b): the outer-face divergence does NOT track the edge vorticity
(direct-solver nest, face residual 1.28e-04, zeta edge/interior 323; lowmem 2.85e-01 -> 778 and
2.17e-01 -> 217 -- no monotone relationship).  But that was three points at one instant.  This
script builds the controlled matrix and, crucially, converts the answer into the number the
science actually needs: a TRUSTED-INTERIOR MARGIN IN METRES.

METRIC.  A nest is finer than its parent, so it legitimately resolves more -- a raw nest-vs-parent
difference is not contamination.  We therefore block-average the nest field back onto its parent
cells (the scales the parent can represent) and compare there:

    mismatch(d) = < | zeta_nest_restricted - zeta_parent | >   over cells at distance d from the
                  nest boundary, normalised by the interior plateau value

Contamination penetration = the distance at which mismatch(d) falls to within `PLATEAU_TOL` of
its interior plateau.  That is a physical LENGTH, reported in metres, and it is what the trusted
margin must exceed.

VARIED:  sponge physical width, sponge rate, relax-before/after-projection ordering,
parent/nest refinement ratio, projection path (direct vs low-memory, via nest size).
MEASURED: zeta mismatch, divergence, and the penetration depth, each vs distance in METRES.

Run:  python scratchpad/edge_vorticity_matrix.py            (CPU, ~minutes)
Env:  DEV=gpu to use the GPU; STEPS=n to change the evolution window.
"""
