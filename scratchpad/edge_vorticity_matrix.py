def matured_parent(nx=60, nz=40):
    sc = build_storm_config(preset="storm", nx=nx, ny=nx, nz=nz, Lx=nx * 600.0, Ly=nx * 600.0,
                            Lz=15000.0, duration=1.0, dt_max=3.0, drag=True, z_stretch=1.05,
                            C_s=0.20, device=DEV, periodic=True)
    sc.sim.physics.bubble_dtheta = 5.0
    p = StormSimulation(sc)
    for _ in range(20):
        p._step(p._dt())
    return p


def _zeta2d(sim, z_m=100.0):
    g = sim.grid; to = g.backend.to_cpu
    z = np.asarray(to(rot.vertical_vorticity(sim.state, g)))
    zc = np.asarray(to(g.zc))
    return z[:, :, int(np.argmin(np.abs(zc - z_m)))]


def _restrict(a, r):
    """Block-average a nest field onto its parent cells (refinement ratio r)."""
    n0, n1 = a.shape
    m0, m1 = n0 // r, n1 // r
    return a[:m0 * r, :m1 * r].reshape(m0, r, m1, r).mean(axis=(1, 3))


def measure(parent, nest, spec, refine):
    """Mismatch and divergence as a function of distance from the nest boundary, in METRES."""
    g = nest.grid
    zn = _restrict(np.abs(_zeta2d(nest)), refine)              # on parent-representable scales
    # the parent cells the nest covers
    i0 = int(round(spec.x0 / parent.grid.dx)); j0 = int(round(spec.y0 / parent.grid.dy))
    zp = np.abs(_zeta2d(parent))[i0:i0 + zn.shape[0], j0:j0 + zn.shape[1]]
    m = np.abs(zn - zp)                                        # mismatch on parent scales
    n = m.shape[0]
    idx = np.arange(n)
    db = np.minimum(np.minimum(idx[:, None], n - 1 - idx[:, None]),
                    np.minimum(idx[None, :], n - 1 - idx[None, :]))
    dx_p = float(parent.grid.dx)
    prof = []
    for d in range(0, n // 2):
        sel = db == d
        if sel.any():
            prof.append((d * dx_p, float(m[sel].mean())))
    # interior plateau = mean over the inner half of the profile
    tail = [v for _, v in prof[len(prof) // 2:]]
    plateau = float(np.mean(tail)) if tail else float("nan")
    # penetration: first distance at which the mismatch drops to within tol of the plateau
    pen = float("nan")
    for dm, v in prof:
        if plateau > 0 and v <= PLATEAU_TOL * plateau:
            pen = dm
            break
    # divergence, on the nest's own mesh
    to = g.backend.to_cpu
    zf = np.asarray(to(g.zf)); dzc = g.xp.asarray(zf[1:] - zf[:-1])
    dv = np.abs(np.asarray(to(anelastic_divergence(nest.state.u, nest.state.v, nest.state.w,
                                                   nest.rho0_c, nest.rho0_wface,
                                                   g.dx, g.dy, dzc))))
    u = np.asarray(to(nest.state.u)); rc = np.asarray(to(nest.rho0_c))
    dv = dv / float(rc.max() * max(np.abs(u).max(), 1e-9) / g.dx)
    nn = dv.shape[0]; ii = np.arange(nn)
    dbn = np.minimum(np.minimum(ii[:, None], nn - 1 - ii[:, None]),
                     np.minimum(ii[None, :], nn - 1 - ii[None, :]))
    return {"profile_m": prof, "plateau": plateau, "penetration_m": pen,
            "edge_mismatch": prof[0][1] if prof else float("nan"),
            "edge_over_plateau": (prof[0][1] / plateau) if (prof and plateau > 0) else float("nan"),
            "div_face0": float(dv[dbn == 0].max()), "div_interior": float(dv[dbn >= 12].max())}


def run_case(parent, sponge_m, rate, before, refine, ncx, nz):
    def spec_fn(g):
        return nst.NestSpec.aligned(g, i0=10, j0=10, ncx=ncx, ncy=ncx, refine=refine, nz=nz,
                                    z_stretch=1.077, relax_width_m=sponge_m, relax_rate=rate,
                                    relax_before_project=before)
    sims, _ = nst.run_multilevel_nest(parent, [spec_fn], window=STEPS * float(parent._dt()))
    nest = sims[-1]
    return measure(parent, nest, nest.spec, refine), nest


